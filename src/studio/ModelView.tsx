import { useEffect, useRef, useState } from 'react';
import { PANEL_IDS, type Analysis, type Design, type LoadNodeId, type PanelId, type RankedBraces } from '../shared';
import { createBraceMember } from '../structures';
import { DEFORMATION_SCALE } from './BridgeCanvas';
import { drawModel, type DrawMode, type ViewMode } from './drawModel';
import type { AnalysisSuccess, Design as DrawDesign } from './drawTypes';

type ModelMode = 'iso' | 'side' | 'deflect' | 'forces';
const MODES: readonly { readonly id: ModelMode; readonly label: string; readonly needsResults: boolean }[] = [
  { id: 'iso', label: '3D view', needsResults: false },
  { id: 'side', label: 'Elevation', needsResults: false },
  { id: 'deflect', label: 'Deflection', needsResults: true },
  { id: 'forces', label: 'Member forces', needsResults: true },
];
const WIDTH = 760;
const HEIGHT = 400;

/** Presentation-only adapters: the renderer reads plain geometry, never engine modules. */
export function toDrawDesign(baseline: Design): DrawDesign {
  return {
    nodes: baseline.nodes.map(node => ({ id: node.id, x: node.xMm, y: node.yMm })),
    members: baseline.members,
    supports: baseline.nodes.filter(node => node.restrained.x || node.restrained.y)
      .map(node => ({ nodeId: node.id, fixedX: node.restrained.x, fixedY: node.restrained.y })),
    braceOptions: PANEL_IDS.map(id => ({ panelId: id, label: id, member: createBraceMember(id) })),
  };
}
export const toDrawAnalysis = (analysis: Analysis): AnalysisSuccess => ({
  displacementsMm: analysis.displacementMmByNode, memberForcesN: analysis.axialForceNByMember,
});

export interface ModelViewProps {
  baseline: Design;
  loadNodeId: LoadNodeId;
  panelId: PanelId | null;
  results: RankedBraces | null;
  locked: boolean;
}

/**
 * Shaded tabletop model of the same truss the engineering drawing below edits. It is a picture,
 * not a control: load and panel changes happen in the drawing and the choice tiles.
 */
export function ModelView({ baseline, loadNodeId, panelId, results, locked }: ModelViewProps) {
  const [mode, setMode] = useState<ModelMode>('iso');
  const hadResults = useRef(results !== null);
  // The reveal is the moment: show the magnified deflection as soon as results first appear.
  useEffect(() => {
    if (results && !hadResults.current) setMode('deflect');
    hadResults.current = results !== null;
  }, [results]);
  const chosen = panelId && results ? results.candidates[panelId] : null;
  const shown: ModelMode = chosen || (mode !== 'deflect' && mode !== 'forces') ? mode : 'iso';
  const view: ViewMode = shown === 'side' || shown === 'deflect' ? 'side' : 'iso';
  const drawMode: DrawMode = shown === 'deflect' || shown === 'forces' ? shown : 'layout';
  const drawn = drawModel({
    design: toDrawDesign(baseline), loadNodeId,
    previewPanelId: locked ? null : panelId, committedPanelId: locked ? panelId : null, locked,
    view, mode: drawMode, orbit: 0, width: WIDTH, height: HEIGHT, deformationScale: DEFORMATION_SCALE,
    ...(results && chosen
      ? { original: toDrawAnalysis(results.baseline.analysis), modified: toDrawAnalysis(chosen.analysis) }
      : {}),
  });
  const note = shown === 'deflect'
    ? `Dashed = original. Solid = braced. Both magnified ${DEFORMATION_SCALE}×.`
    : shown === 'forces' ? 'Teal = tension. Rust = compression. Gray = zero force.' : '';
  return <figure className="model-view">
    <div className="model-view-controls" role="group" aria-label="Model view">
      {MODES.filter(item => !item.needsResults || chosen).map(item => <button key={item.id} type="button"
        aria-pressed={item.id === shown} onClick={() => setMode(item.id)}>{item.label}</button>)}
    </div>
    {/* Markup is generated by drawModel from typed numeric data only. */}
    <svg className="model-view-svg" role="img" aria-label={drawn.ariaLabel} viewBox={drawn.viewBox}
      dangerouslySetInnerHTML={{ __html: drawn.svgInner }} />
    <figcaption>{note || 'Shaded model of the tabletop truss. Edit the load and panel in the drawing below.'}</figcaption>
  </figure>;
}
